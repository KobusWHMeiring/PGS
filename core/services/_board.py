"""The public board at `/building/` — the published set, shaped for the template.

Two rules from `build_principles.md` meet here:

* **§II — no logic in templates.** The column *titles*, the order, and the decision to drop
  an empty column all live here. A template that held "Shipped" would be a second place to
  change a word, and the first place would be `core/services/_board_data.py`, which is
  generated and must not hold presentation.
* **§I — code encodes the process, data encodes the group.** The board is neither: it is the
  release artefact in `_board_data.py`, generated by `scripts/board.py` from the PRDs that
  carry `**Public:** yes`. Nothing here reads `product/` at request time, so a PRD edit never
  changes the live site without a deploy (D74b).

**The standpoint line is load-bearing.** A roadmap card is not a certification status, and the
OPP's "membership is not certification" rule applies to every new surface: a visitor who reads
"Every document can be opened and read" beside a seal could reasonably infer something about a
farm. So the page states what it is, in a field rather than in the template, where
`core/tests/test_public.py` can assert it is present.
"""

from __future__ import annotations

from dataclasses import dataclass

from core.services._board_data import COLUMN_ORDER, CURATED

#: The column labels. Deliberately not in the artefact: renaming a column must not force a
#: regeneration, and the artefact is data.
COLUMN_TITLES: dict[str, str] = {
    "refinement": "In design",
    "ready": "Up next",
    "in_progress": "Building",
    "done": "Shipped",
}

#: Said once, on the page, in the same breath as the cards. A board of futures is an easy
#: thing to over-read.
STANDPOINT = (
    "A development log, not a statement about any farm's certification status. "
    "No dates are promised, and nothing here is a commitment."
)

#: What the page says when nothing is marked publishable. Reached by deleting every
#: `**Public:** yes` line and regenerating — which must render a sentence, not a heading over
#: an empty grid.
EMPTY_MESSAGE = (
    "Nothing is published here at the moment. The work continues; "
    "the documents and the standard remain readable in the meantime."
)


@dataclass(frozen=True)
class Card:
    """One card: a title and one sentence. No date, no status, no owner, no link.

    `updated` is in the artefact because it *orders* the Shipped column, and is deliberately
    dropped here: a board that prints how long each item has sat there invites a reader to
    judge velocity and abandonment (D74b).
    """

    title: str
    summary: str


@dataclass(frozen=True)
class Column:
    """One column. `key` is the artefact's bucket; `title` is what a visitor reads."""

    key: str
    title: str
    cards: tuple[Card, ...]


@dataclass(frozen=True)
class Board:
    columns: tuple[Column, ...]
    standpoint: str
    empty_message: str

    @property
    def is_empty(self) -> bool:
        return not self.columns

    @property
    def card_count(self) -> int:
        return sum(len(column.cards) for column in self.columns)


def board() -> Board:
    """The board as the template needs it.

    In:      nothing — the artefact is a module, imported once.
    Out:     `Board` with one `Column` per non-empty column, in board order.
    Side effects: none.
    Fails:   never on a well-formed artefact. A column key the artefact does not declare is
             dropped rather than rendered with an empty label, because a blank column heading
             is worse than a missing column.
    """
    grouped: dict[str, list[Card]] = {key: [] for key in COLUMN_ORDER}
    for row in CURATED:
        key = row["column"]
        if key in grouped:
            grouped[key].append(Card(title=row["title"], summary=row["summary"]))

    columns = tuple(
        Column(key=key, title=COLUMN_TITLES[key], cards=tuple(grouped[key]))
        for key in COLUMN_ORDER
        if key in COLUMN_TITLES and grouped[key]
    )
    return Board(columns=columns, standpoint=STANDPOINT, empty_message=EMPTY_MESSAGE)


def board_context() -> dict:
    """The context fragment `/building/` adds to `public_context`."""
    return {"board": board()}
