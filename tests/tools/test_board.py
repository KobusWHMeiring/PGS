"""`scripts/board.py` — the artefact, and the three things it must refuse.

The board is the only page on the public site whose content comes from a directory of
engineering notes, so the interesting failures are all about *what reaches it*:

1. **A silent drop.** An opted-in PRD that cannot become a card is a mistake to fix, not a
   state to record — the generator exits non-zero. A filter would make the board look complete
   while a maintained item was missing (`testing_hazards.md` §1.6 with a directory behind it).
2. **A claim.** A summary using a forbidden term writes an artefact that renders 200 and fails
   `test_claim_discipline.py` one gate later, where the file that caused it is not named.
3. **A stale artefact.** `--check` is what `deploy/deploy.sh` runs *before* it backs anything
   up. A comparison with a hole in it (ignoring a generated-at line, say) is worse than none.

`build_source` is a pure function of the payload, deliberately: `--check` compares bytes, so
anything nondeterministic in it makes the check fail on a tree nobody touched.
"""

from __future__ import annotations

import json

import pytest

import scripts.board as board
from scripts.board import arrange, build_source, claim_violations, load_backlog_module, main
from tests.tools.test_backlog_board_json import _prd


def _card(title="A card", summary="A summary.", column="ready", updated="2026-10-01", rel="ready/x.md"):
    return {
        "title": title,
        "summary": summary,
        "column": column,
        "updated": updated,
        "rel": rel,
    }


def _payload(cards):
    return {
        "version": 1,
        "cards": list(cards),
        "rejected": [],
        "digest": "sha256:" + "0" * 64,
    }


# --- The artefact is data, and it is a subset ----------------------------------


def test_the_artefact_carries_every_card_and_nothing_else():
    """The subset property, which is the whole safety argument: the artefact may lose a card
    to the Shipped cap and may never gain one."""
    payload = _payload([
        _card(title="One", column="ready"),
        _card(title="Two", column="refinement"),
    ])

    source = build_source(payload)
    namespace: dict = {}
    exec(source, namespace)  # noqa: S102 — the artefact is generated by us, in a test

    titles = {card["title"] for card in namespace["CURATED"]}
    assert titles == {"One", "Two"}
    assert titles <= {card["title"] for card in payload["cards"]}
    assert namespace["SOURCE_DIGEST"] == payload["digest"]


def test_the_artefact_names_its_generator_and_carries_no_paths():
    payload = _payload([_card(rel="In Progress/a_very_identifiable_file.md")])
    source = build_source(payload)

    assert "GENERATED, do not edit by hand" in source
    assert "python scripts/board.py" in source
    assert "a_very_identifiable_file" not in source, "a repo path reached a public module"
    assert "**Status:**" not in source


def test_an_empty_board_says_so_in_the_artefact():
    """Deleting every `**Public:** yes` must produce a valid module, not a syntax error and not
    an artefact that renders a heading over nothing."""
    source = build_source(_payload([]))
    namespace: dict = {}
    exec(source, namespace)  # noqa: S102

    assert namespace["CURATED"] == ()
    assert "Nothing is marked" in source


# --- Order and cap ------------------------------------------------------------


def test_shipped_is_newest_first_and_capped():
    cards = [
        _card(title=f"Ship {index}", column="done", updated=f"2026-10-{index:02d}", rel=f"done/{index}.md")
        for index in range(1, 9)
    ]

    titles = [card["title"] for card in arrange(cards)]

    assert titles == [f"Ship {index}" for index in (8, 7, 6, 5, 4, 3)]
    assert len(titles) == board.DONE_LIMIT


def test_columns_come_out_in_board_order():
    cards = [
        _card(title="Designed", column="refinement"),
        _card(title="Building", column="in_progress"),
        _card(title="Next", column="ready"),
        _card(title="Shipped", column="done"),
    ]
    assert [card["column"] for card in arrange(cards)] == [
        "refinement",
        "ready",
        "in_progress",
        "done",
    ]


def test_arranging_is_stable_across_runs():
    """`--check` compares bytes; a set or an unstable sort makes it flaky in a way that looks
    like a real drift."""
    cards = [
        _card(title="B", column="ready", rel="ready/b.md"),
        _card(title="A", column="ready", rel="ready/a.md"),
        _card(title="C", column="done", updated="2026-10-01", rel="done/c.md"),
    ]
    assert arrange(cards) == arrange(list(reversed(cards)))


# --- The three refusals --------------------------------------------------------


def test_a_forbidden_term_in_a_summary_is_refused(tmp_path, monkeypatch):
    """The summary is written by a person, so the check names the file and the term — a red
    public-surface test in another module would not say which."""
    violations = claim_violations([_card(summary="Our pasture raised beef.")])
    assert len(violations) == 1
    assert "pasture raised" in violations[0]
    assert "ready/x.md" in violations[0]


def test_a_rejected_card_stops_the_generator(tmp_path, monkeypatch):
    module = load_backlog_module()
    monkeypatch.setattr(module, "BACKLOG", tmp_path)
    _prd(tmp_path, "ready/no_summary.md", public=True)

    artefact = tmp_path / "board_data.py"
    monkeypatch.setattr(board, "ARTEFACT", artefact)

    assert main([], module=module) == 1
    assert not artefact.exists(), "a refused build must not write a partial artefact"


def test_a_claim_in_a_published_summary_stops_the_generator(tmp_path, monkeypatch, capsys):
    module = load_backlog_module()
    monkeypatch.setattr(module, "BACKLOG", tmp_path)
    _prd(tmp_path, "ready/bad.md", summary="GMO free produce, biodynamic methods.")

    artefact = tmp_path / "board_data.py"
    monkeypatch.setattr(board, "ARTEFACT", artefact)

    assert main([], module=module) == 1
    assert "gmo free" in capsys.readouterr().err.lower()
    assert not artefact.exists()


# --- Write and check ----------------------------------------------------------


def test_check_passes_on_a_fresh_artefact_and_fails_when_the_tree_moves(tmp_path, monkeypatch, capsys):
    """The deploy contract: `--check` is silent on success and loud, with the command, on drift."""
    module = load_backlog_module()
    monkeypatch.setattr(module, "BACKLOG", tmp_path)
    _prd(tmp_path, "ready/card.md", summary="A card.")

    artefact = tmp_path / "board_data.py"
    monkeypatch.setattr(board, "ARTEFACT", artefact)

    assert main([], module=module) == 0
    assert main(["--check"], module=module) == 0

    _prd(tmp_path, "ready/card.md", summary="A card, edited.")
    capsys.readouterr()
    assert main(["--check"], module=module) == 1
    assert "python scripts/board.py" in capsys.readouterr().err


def test_check_fails_when_the_artefact_is_missing(tmp_path, monkeypatch, capsys):
    module = load_backlog_module()
    monkeypatch.setattr(module, "BACKLOG", tmp_path)
    _prd(tmp_path, "ready/card.md", summary="A card.")
    monkeypatch.setattr(board, "ARTEFACT", tmp_path / "nothing_here.py")

    assert main(["--check"], module=module) == 1
    assert "missing" in capsys.readouterr().err.lower()


# --- The real tree, and the loader's own hazard -------------------------------


def test_the_loader_reads_backlog_py_and_not_the_directory_of_the_same_name():
    """`product/` holds both `backlog.py` and `backlog/`. The module wins today only because
    the directory has no `__init__.py`; adding one would silently flip the import to the
    package. Loading by path makes that impossible."""
    module = load_backlog_module()
    assert module.__file__.endswith("backlog.py")
    assert hasattr(module, "board_payload")


def test_the_shipped_artefact_matches_the_tree():
    """The same check the deploy runs, in the lane a developer actually runs. If this fails,
    run `python scripts/board.py` — do not edit `_board_data.py`."""
    assert main(["--check"]) == 0


def test_the_artefact_is_importable_and_json_shaped():
    """The service imports it; a syntax error here is a 500 on a public page."""
    from core.services import _board_data

    assert _board_data.COLUMN_ORDER
    assert isinstance(_board_data.CURATED, tuple)
    for card in _board_data.CURATED:
        assert set(card) == {"title", "summary", "column", "updated"}
        assert card["column"] in _board_data.COLUMN_ORDER
        assert len(card["summary"]) <= 180
    json.dumps(list(_board_data.CURATED))
